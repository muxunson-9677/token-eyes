"use strict";

const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..");
const canonicalPath = path.join(repoRoot, "shared", "agent-registry.json");
const defaultTargetPath = path.join(
  repoRoot,
  "dashboard",
  "src",
  "lib",
  "agent-adapters-dashboard.ts",
);

function validateRegistry(registry) {
  if (registry?.schema_version !== 1 || !Array.isArray(registry.adapters)) {
    throw new Error("Invalid shared/agent-registry.json");
  }
}

function projectDashboardAgents(registry) {
  validateRegistry(registry);
  const identities = new Map();
  for (const adapter of registry.adapters) {
    if (identities.has(adapter.usage_identity)) continue;
    identities.set(adapter.usage_identity, {
      id: adapter.usage_identity,
      displayName: adapter.display_name,
      usageIdentity: adapter.usage_identity,
      queueSource: adapter.queue_source,
    });
  }
  return Array.from(identities.values());
}

function quote(value) {
  return JSON.stringify(value);
}

function renderDashboardRegistry(registry) {
  const agents = projectDashboardAgents(registry);
  const rows = agents.map((agent) => (
    `  { id: ${quote(agent.id)}, displayName: ${quote(agent.displayName)}, usageIdentity: ${quote(agent.usageIdentity)}, queueSource: ${quote(agent.queueSource)} },`
  ));
  return `// Generated by scripts/generate-agent-dashboard-registry.cjs.
// Source of truth: shared/agent-registry.json. Do not edit this file directly.

export interface DashboardAgent {
  id: string;
  displayName: string;
  usageIdentity: string;
  queueSource: string;
}

export const DASHBOARD_AGENTS: readonly DashboardAgent[] = [
${rows.join("\n")}
] as const;

const SOURCE_TO_AGENT_ID: ReadonlyMap<string, string> = (() => {
  const map = new Map<string, string>();
  for (const agent of DASHBOARD_AGENTS) {
    if (!map.has(agent.queueSource)) map.set(agent.queueSource, agent.id);
  }
  return map;
})();

export function getAgentIdByQueueSource(queueSource: string): string | undefined {
  return SOURCE_TO_AGENT_ID.get(queueSource);
}

export function getAgentDisplayNameByQueueSource(queueSource: string): string {
  const agent = DASHBOARD_AGENTS.find((entry) => entry.queueSource === queueSource);
  return agent?.displayName ?? queueSource;
}
`;
}

function parseArgs(argv) {
  const args = new Set(argv);
  const targetIndex = argv.indexOf("--target");
  return {
    check: args.has("--check"),
    write: args.has("--write"),
    targetPath: targetIndex >= 0 ? path.resolve(argv[targetIndex + 1] || "") : defaultTargetPath,
  };
}

function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  if (options.check === options.write) {
    throw new Error("Choose exactly one mode: --check or --write");
  }
  const registry = JSON.parse(fs.readFileSync(canonicalPath, "utf8"));
  const output = Buffer.from(renderDashboardRegistry(registry), "utf8");
  if (options.write) {
    fs.writeFileSync(options.targetPath, output);
    return;
  }

  const tempRoot = path.join(repoRoot, "src-tauri", "target", "agent-registry-check");
  fs.mkdirSync(tempRoot, { recursive: true });
  const tempDir = fs.mkdtempSync(path.join(tempRoot, "projection-"));
  const tempOutput = path.join(tempDir, "agent-adapters-dashboard.ts");
  try {
    fs.writeFileSync(tempOutput, output);
    const actual = fs.readFileSync(options.targetPath);
    if (!actual.equals(fs.readFileSync(tempOutput))) {
      throw new Error(
        "Dashboard agent registry drifted. Run: node scripts/generate-agent-dashboard-registry.cjs --write",
      );
    }
  } finally {
    fs.rmSync(tempDir, { recursive: true, force: true });
  }
}

if (require.main === module) {
  try {
    run();
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  projectDashboardAgents,
  renderDashboardRegistry,
  run,
};
