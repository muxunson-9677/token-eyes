-- Atomic, server-priced leaderboard refresh from compact per-device states.
-- Apply after leaderboard-device-state.sql, leaderboard-actual-cost-state.sql,
-- and leaderboard-model-pricing.sql.

create extension if not exists pgcrypto;

-- Keep the existing production snapshot table intact. Its legacy NOT NULL
-- columns and uniqueness constraints are incompatible with metric/source rows,
-- so the new refresh pipeline writes to a versioned table.
create table if not exists public.tokentracker_leaderboard_snapshots_v2 (
  snapshot_row_id bigint generated by default as identity primary key,
  period text not null check (period in ('today', 'week', '30d', 'month', 'total')),
  metric text not null check (metric in ('tokens', 'estimated_spend', 'actual_cost')),
  source text not null,
  from_day date not null,
  to_day date not null,
  rank integer not null check (rank > 0),
  participant_count integer not null check (participant_count > 0),
  user_id uuid not null,
  public_entry_id text not null check (public_entry_id ~ '^[a-f0-9]{64}$'),
  total_tokens numeric(30,0) not null check (total_tokens >= 0),
  estimated_cost_usd numeric(30,6) not null check (estimated_cost_usd >= 0),
  actual_cost_usd numeric(20,6),
  source_breakdown jsonb not null default '[]'::jsonb,
  gpt_tokens numeric(30,0) not null default 0,
  claude_tokens numeric(30,0) not null default 0,
  gemini_tokens numeric(30,0) not null default 0,
  cursor_tokens numeric(30,0) not null default 0,
  hermes_tokens numeric(30,0) not null default 0,
  copilot_tokens numeric(30,0) not null default 0,
  display_name text not null default 'Anonymous',
  avatar_url text,
  github_url text,
  pricing_version text not null,
  generated_at timestamptz not null,
  snapshot_run_id uuid not null,
  is_public boolean not null default true
);

alter table public.tokentracker_leaderboard_snapshots_v2
  alter column estimated_cost_usd type numeric(30,6);

alter table public.tokentracker_leaderboard_snapshots_v2
  add column if not exists public_entry_id text;

alter table public.tokentracker_leaderboard_snapshots_v2
  add column if not exists participant_count integer;

update public.tokentracker_leaderboard_snapshots_v2
set participant_count = 1
where participant_count is null;

alter table public.tokentracker_leaderboard_snapshots_v2
  alter column participant_count set not null;

update public.tokentracker_leaderboard_snapshots_v2
set public_entry_id = encode(digest(user_id::text, 'sha256'), 'hex')
where public_entry_id is null;

alter table public.tokentracker_leaderboard_snapshots_v2
  alter column public_entry_id set not null;

create index if not exists tokentracker_leaderboard_snapshot_v2_rank_idx
  on public.tokentracker_leaderboard_snapshots_v2
  (period, metric, source, snapshot_run_id, rank);

create index if not exists tokentracker_leaderboard_snapshot_v2_user_idx
  on public.tokentracker_leaderboard_snapshots_v2
  (user_id, period, metric, source, snapshot_run_id);

create or replace function public.refresh_leaderboard_snapshot_dimensions(
  p_dimensions jsonb
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $function$
declare
  v_started_at timestamptz := clock_timestamp();
  v_generated_at timestamptz := now();
  v_shanghai_day date := (now() at time zone 'Asia/Shanghai')::date;
  v_snapshot_run_id uuid := gen_random_uuid();
  v_allowed_periods text[] := array['today', 'week', '30d', 'month', 'total'];
  v_allowed_sources text[] := array[
    'all', 'claude', 'codex', 'every-code', 'cursor', 'trae', 'gemini',
    'opencode', 'openclaw', 'kilo-cli', 'kilocode', 'roocode', 'kiro',
    'hermes', 'kimi', 'kimi-code', 'codebuddy', 'workbuddy', 'omp', 'pi',
    'craft', 'grok', 'copilot', 'zed', 'goose', 'droid', 'antigravity',
    'deepseek-harness'
  ];
  v_periods text[];
  v_pricing_version text;
  v_pricing_version_count integer;
  v_inserted integer := 0;
  v_row_counts jsonb := '{}'::jsonb;
  v_static_dimensions jsonb := '[]'::jsonb;
begin
  -- One writer at a time. The transaction keeps the previous complete run
  -- visible if any validation, pricing, or insert operation fails.
  perform pg_advisory_xact_lock(hashtext('tokentracker:leaderboard-refresh'));

  if jsonb_typeof(p_dimensions) <> 'array'
     or jsonb_array_length(p_dimensions) < 1
     or jsonb_array_length(p_dimensions) > 285 then
    raise exception 'p_dimensions must contain between 1 and 285 fixed keys';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_dimensions) dimension
    where jsonb_typeof(dimension) <> 'object'
      or dimension - array['period', 'metric', 'source'] <> '{}'::jsonb
      or not (dimension ?& array['period', 'metric', 'source'])
      or not ((dimension ->> 'period') = any(v_allowed_periods))
      or not ((dimension ->> 'metric') = any(array['tokens', 'estimated_spend', 'actual_cost']))
      or not ((dimension ->> 'source') = any(v_allowed_sources))
      or ((dimension ->> 'metric') = 'actual_cost' and (dimension ->> 'source') <> 'all')
  ) then
    raise exception 'p_dimensions contains a non-whitelisted key';
  end if;

  select array_agg(distinct dimension ->> 'period')
  into v_periods
  from jsonb_array_elements(p_dimensions) dimension;

  select min(pricing_version), count(distinct pricing_version)
  into v_pricing_version, v_pricing_version_count
  from public.tokentracker_model_pricing;

  if v_pricing_version is null or v_pricing_version_count <> 1 then
    raise exception 'pricing seed must contain exactly one active version';
  end if;

  with
  selected_dimensions as (
    select distinct
      dimension ->> 'period' as period,
      dimension ->> 'metric' as metric,
      dimension ->> 'source' as source
    from jsonb_array_elements(p_dimensions) dimension
  ),
  selected_periods as (
    select period
    from unnest(v_periods) as selected(period)
    where period = any(v_allowed_periods)
  ),
  expanded as (
    select
      state.user_id,
      selected.period,
      item.value ->> 0 as source,
      item.value ->> 1 as model,
      (item.value ->> 2)::numeric(30,0) as input_tokens,
      (item.value ->> 3)::numeric(30,0) as output_tokens,
      (item.value ->> 4)::numeric(30,0) as cached_input_tokens,
      (item.value ->> 5)::numeric(30,0) as cache_creation_input_tokens,
      (item.value ->> 6)::numeric(30,0) as reasoning_output_tokens
    from public.tokentracker_leaderboard_device_state state
    cross join selected_periods selected
    cross join lateral jsonb_array_elements(
      case
        when jsonb_typeof(state.payload -> 'periods' -> selected.period) = 'array'
        then state.payload -> 'periods' -> selected.period
        else '[]'::jsonb
      end
    ) as item(value)
    where jsonb_typeof(item.value) = 'array'
      and jsonb_array_length(item.value) = 7
      and item.value ->> 0 <> ''
      and item.value ->> 1 <> ''
      and item.value ->> 2 ~ '^[0-9]+$'
      and item.value ->> 3 ~ '^[0-9]+$'
      and item.value ->> 4 ~ '^[0-9]+$'
      and item.value ->> 5 ~ '^[0-9]+$'
      and item.value ->> 6 ~ '^[0-9]+$'
      and (state.captured_at at time zone 'Asia/Shanghai')::date <= v_shanghai_day
      and (
        selected.period = 'total'
        or (
          selected.period = 'today'
          and (state.captured_at at time zone 'Asia/Shanghai')::date = v_shanghai_day
        )
        or (
          selected.period = 'week'
          and (state.captured_at at time zone 'Asia/Shanghai')::date
            >= v_shanghai_day - (extract(isodow from v_shanghai_day)::integer - 1)
        )
        or (
          selected.period = '30d'
          and (state.captured_at at time zone 'Asia/Shanghai')::date
            >= v_shanghai_day - 29
        )
        or (
          selected.period = 'month'
          and (state.captured_at at time zone 'Asia/Shanghai')::date
            >= v_shanghai_day - (extract(day from v_shanghai_day)::integer - 1)
        )
      )
  ),
  by_user_source_model as (
    select
      user_id,
      period,
      source,
      model,
      sum(input_tokens)::numeric(30,0) as input_tokens,
      sum(output_tokens)::numeric(30,0) as output_tokens,
      sum(cached_input_tokens)::numeric(30,0) as cached_input_tokens,
      sum(cache_creation_input_tokens)::numeric(30,0) as cache_creation_input_tokens,
      sum(reasoning_output_tokens)::numeric(30,0) as reasoning_output_tokens
    from expanded
    group by user_id, period, source, model
  ),
  server_priced as (
    select
      grouped.*,
      (
        grouped.input_tokens
        + grouped.output_tokens
        + grouped.cached_input_tokens
        + grouped.cache_creation_input_tokens
        + case
            when grouped.source in ('codex', 'every-code') then 0
            else grouped.reasoning_output_tokens
          end
      )::numeric(30,0) as total_tokens,
      (
        grouped.input_tokens * coalesce(pricing.input_usd_per_token, 0)
        + grouped.output_tokens * coalesce(pricing.output_usd_per_token, 0)
        + grouped.cached_input_tokens * coalesce(pricing.cache_read_usd_per_token, 0)
        + grouped.cache_creation_input_tokens * coalesce(pricing.cache_write_usd_per_token, 0)
        + case
            when grouped.source in ('codex', 'every-code') then 0
            else grouped.reasoning_output_tokens * coalesce(pricing.output_usd_per_token, 0)
          end
      )::numeric(30,6) as estimated_cost_usd,
      pricing.pricing_key
    from by_user_source_model grouped
    left join lateral (
      select candidate.*
      from public.tokentracker_model_pricing candidate
      where candidate.pricing_version = v_pricing_version
        and (
          candidate.pricing_key = grouped.model
          or lower(candidate.pricing_key) = lower(grouped.model)
          or lower(candidate.pricing_key)
            = lower(regexp_replace(grouped.model, '^.*/', ''))
        )
      order by
        (candidate.pricing_key = grouped.model) desc,
        (lower(candidate.pricing_key) = lower(grouped.model)) desc,
        char_length(candidate.pricing_key),
        candidate.pricing_key
      limit 1
    ) pricing on true
  ),
  public_priced as (
    -- Privacy filter happens before any rank window, so a private high-volume
    -- user cannot create a visible gap in dense_rank().
    select priced.*
    from server_priced priced
    join public.tokentracker_user_settings settings
      on settings.user_id = priced.user_id
      and settings.leaderboard_public = true
  ),
  per_source as (
    select
      user_id,
      period,
      source,
      sum(total_tokens)::numeric(30,0) as total_tokens,
      sum(estimated_cost_usd)::numeric(30,6) as estimated_cost_usd,
      sum(
        case when pricing_key is null then total_tokens else 0 end
      )::numeric(30,0) as unpriced_tokens
    from public_priced
    group by user_id, period, source
  ),
  per_user as (
    select
      user_id,
      period,
      sum(total_tokens)::numeric(30,0) as total_tokens,
      sum(estimated_cost_usd)::numeric(30,6) as estimated_cost_usd,
      jsonb_agg(
        jsonb_build_object(
          'source', source,
          'total_tokens', total_tokens,
          'estimated_cost_usd', estimated_cost_usd,
          'unpriced_tokens', unpriced_tokens
        )
        order by total_tokens desc, source
      ) as source_breakdown
    from per_source
    group by user_id, period
  ),
  actual_values as (
    select
      totals.*,
      case totals.period
        when 'today' then actual.today_usd
        when 'week' then actual.week_usd
        when '30d' then actual."30d_usd"
        when 'month' then actual.month_usd
        when 'total' then actual.total_usd
      end as actual_cost_usd
    from per_user totals
    join public.tokentracker_actual_cost_state actual
      on actual.user_id = totals.user_id
      and actual.share_actual_cost = true
      and (actual.captured_at at time zone 'Asia/Shanghai')::date <= v_shanghai_day
      and (
        totals.period = 'total'
        or (
          totals.period = 'today'
          and (actual.captured_at at time zone 'Asia/Shanghai')::date = v_shanghai_day
        )
        or (
          totals.period = 'week'
          and (actual.captured_at at time zone 'Asia/Shanghai')::date
            >= v_shanghai_day - (extract(isodow from v_shanghai_day)::integer - 1)
        )
        or (
          totals.period = '30d'
          and (actual.captured_at at time zone 'Asia/Shanghai')::date = v_shanghai_day
        )
        or (
          totals.period = 'month'
          and (actual.captured_at at time zone 'Asia/Shanghai')::date
            >= v_shanghai_day - (extract(day from v_shanghai_day)::integer - 1)
        )
      )
  ),
  ranked_values as (
    select
      source_rows.user_id,
      source_rows.period,
      'tokens'::text as metric,
      source_rows.source,
      source_rows.total_tokens,
      source_rows.estimated_cost_usd,
      null::numeric(20,6) as actual_cost_usd,
      jsonb_build_array(jsonb_build_object(
        'source', source_rows.source,
        'total_tokens', source_rows.total_tokens,
        'estimated_cost_usd', source_rows.estimated_cost_usd,
        'unpriced_tokens', source_rows.unpriced_tokens
      )) as source_breakdown,
      source_rows.total_tokens::numeric as sort_value
    from per_source source_rows

    union all

    select
      source_rows.user_id,
      source_rows.period,
      'estimated_spend',
      source_rows.source,
      source_rows.total_tokens,
      source_rows.estimated_cost_usd,
      null::numeric(20,6),
      jsonb_build_array(jsonb_build_object(
        'source', source_rows.source,
        'total_tokens', source_rows.total_tokens,
        'estimated_cost_usd', source_rows.estimated_cost_usd,
        'unpriced_tokens', source_rows.unpriced_tokens
      )),
      source_rows.estimated_cost_usd
    from per_source source_rows

    union all

    select
      totals.user_id,
      totals.period,
      'tokens',
      'all',
      totals.total_tokens,
      totals.estimated_cost_usd,
      null::numeric(20,6),
      totals.source_breakdown,
      totals.total_tokens::numeric
    from per_user totals

    union all

    select
      totals.user_id,
      totals.period,
      'estimated_spend',
      'all',
      totals.total_tokens,
      totals.estimated_cost_usd,
      null::numeric(20,6),
      totals.source_breakdown,
      totals.estimated_cost_usd
    from per_user totals

    union all

    select
      actual.user_id,
      actual.period,
      'actual_cost',
      'all',
      actual.total_tokens,
      actual.estimated_cost_usd,
      actual.actual_cost_usd,
      actual.source_breakdown,
      actual.actual_cost_usd as sort_value
    from actual_values actual
    where actual.actual_cost_usd is not null
  ),
  ranked_all as (
    select
      ranked_input.*,
      row_number() over (
        partition by ranked_input.period, ranked_input.metric, ranked_input.source
        order by ranked_input.sort_value desc, ranked_input.user_id asc
      )::integer as rank,
      count(*) over (
        partition by ranked_input.period, ranked_input.metric, ranked_input.source
      )::integer as participant_count
    from ranked_values ranked_input
  ),
  ranked as (
    select ranked_all.*
    from ranked_all
    join selected_dimensions dimension
      on dimension.period = ranked_all.period
      and dimension.metric = ranked_all.metric
      and dimension.source = ranked_all.source
    where ranked_all.rank <= 50
  ),
  inserted as (
    insert into public.tokentracker_leaderboard_snapshots_v2 (
      period,
      metric,
      source,
      from_day,
      to_day,
      rank,
      participant_count,
      user_id,
      public_entry_id,
      total_tokens,
      estimated_cost_usd,
      actual_cost_usd,
      source_breakdown,
      gpt_tokens,
      claude_tokens,
      gemini_tokens,
      cursor_tokens,
      hermes_tokens,
      copilot_tokens,
      display_name,
      avatar_url,
      github_url,
      pricing_version,
      generated_at,
      snapshot_run_id,
      is_public
    )
    select
      ranked.period,
      ranked.metric,
      ranked.source,
      case ranked.period
        when 'today' then v_shanghai_day
        when 'week' then
          v_shanghai_day - (extract(isodow from v_shanghai_day)::integer - 1)
        when '30d' then v_shanghai_day - 29
        when 'month' then
          v_shanghai_day - (extract(day from v_shanghai_day)::integer - 1)
        else date '1970-01-01'
      end,
      case ranked.period
        when 'today' then v_shanghai_day
        when 'week' then
          v_shanghai_day - (extract(isodow from v_shanghai_day)::integer - 1) + 6
        when '30d' then v_shanghai_day
        when 'month' then
          (
            v_shanghai_day
            - (extract(day from v_shanghai_day)::integer - 1)
            + interval '1 month - 1 day'
          )::date
        else v_shanghai_day
      end,
      ranked.rank,
      ranked.participant_count,
      ranked.user_id,
      encode(digest(ranked.user_id::text, 'sha256'), 'hex'),
      ranked.total_tokens,
      ranked.estimated_cost_usd,
      ranked.actual_cost_usd,
      ranked.source_breakdown,
      coalesce((
        select sum((entry.value ->> 'total_tokens')::numeric(30,0))
        from jsonb_array_elements(ranked.source_breakdown) as entry(value)
        where entry.value ->> 'source' in ('codex', 'every-code')
      ), 0)::numeric(30,0),
      coalesce((
        select sum((entry.value ->> 'total_tokens')::numeric(30,0))
        from jsonb_array_elements(ranked.source_breakdown) as entry(value)
        where entry.value ->> 'source' = 'claude'
      ), 0)::numeric(30,0),
      coalesce((
        select sum((entry.value ->> 'total_tokens')::numeric(30,0))
        from jsonb_array_elements(ranked.source_breakdown) as entry(value)
        where entry.value ->> 'source' = 'gemini'
      ), 0)::numeric(30,0),
      coalesce((
        select sum((entry.value ->> 'total_tokens')::numeric(30,0))
        from jsonb_array_elements(ranked.source_breakdown) as entry(value)
        where entry.value ->> 'source' = 'cursor'
      ), 0)::numeric(30,0),
      coalesce((
        select sum((entry.value ->> 'total_tokens')::numeric(30,0))
        from jsonb_array_elements(ranked.source_breakdown) as entry(value)
        where entry.value ->> 'source' = 'hermes'
      ), 0)::numeric(30,0),
      coalesce((
        select sum((entry.value ->> 'total_tokens')::numeric(30,0))
        from jsonb_array_elements(ranked.source_breakdown) as entry(value)
        where entry.value ->> 'source' = 'copilot'
      ), 0)::numeric(30,0),
      case
        when coalesce(settings.leaderboard_anonymous, false) then 'Anonymous'
        else coalesce(profile.display_name, 'Anonymous')
      end,
      case
        when coalesce(settings.leaderboard_anonymous, false) then null
        -- Public snapshots may reference only the content-addressed avatar
        -- copied to R2 by the authenticated avatar upload edge. Auth-provider
        -- profile URLs are intentionally excluded from the static public path.
        else custom_avatar.avatar_url
      end,
      case
        when coalesce(settings.leaderboard_anonymous, false)
          or not coalesce(settings.show_github_url, false)
        then null
        else settings.github_url
      end,
      v_pricing_version,
      v_generated_at,
      v_snapshot_run_id,
      true
    from ranked
    join public.tokentracker_user_settings settings
      on settings.user_id = ranked.user_id
      and settings.leaderboard_public = true
    left join public.tokentracker_user_profiles profile
      on profile.user_id = ranked.user_id
    left join public.tokentracker_leaderboard_avatar_metadata custom_avatar
      on custom_avatar.user_id = ranked.user_id
    returning period, metric, source
  )
  select count(*)::integer
  into v_inserted
  from inserted;

  -- This statement runs only after the complete new run was inserted. Any
  -- earlier error aborts the transaction and leaves the previous run intact.
  delete from public.tokentracker_leaderboard_snapshots_v2
  where snapshot_run_id is distinct from v_snapshot_run_id
    and exists (
      select 1
      from jsonb_array_elements(p_dimensions) dimension
      where tokentracker_leaderboard_snapshots_v2.period = dimension ->> 'period'
        and tokentracker_leaderboard_snapshots_v2.metric = dimension ->> 'metric'
        and tokentracker_leaderboard_snapshots_v2.source = dimension ->> 'source'
    );

  select coalesce(
    jsonb_object_agg(group_key, row_count),
    '{}'::jsonb
  )
  into v_row_counts
  from (
    select
      period || ':' || metric || ':' || source as group_key,
      count(*) as row_count
    from public.tokentracker_leaderboard_snapshots_v2
    where snapshot_run_id = v_snapshot_run_id
    group by period, metric, source
  ) counts;

  select coalesce(jsonb_agg(jsonb_build_object(
    'period', dimension ->> 'period',
    'metric', dimension ->> 'metric',
    'source', dimension ->> 'source',
    'rows', coalesce((
      select jsonb_agg(jsonb_build_object(
        'rank', snapshot.rank,
        'participant_count', snapshot.participant_count,
        'public_entry_id', snapshot.public_entry_id,
        'display_name', snapshot.display_name,
        'avatar_url', snapshot.avatar_url,
        'github_url', snapshot.github_url,
        'total_tokens', snapshot.total_tokens::text,
        'estimated_cost_usd', snapshot.estimated_cost_usd,
        'actual_cost_usd', snapshot.actual_cost_usd,
        'source_breakdown', snapshot.source_breakdown,
        'pricing_version', snapshot.pricing_version,
        'from_day', snapshot.from_day,
        'to_day', snapshot.to_day
      ) order by snapshot.rank)
      from public.tokentracker_leaderboard_snapshots_v2 snapshot
      where snapshot.snapshot_run_id = v_snapshot_run_id
        and snapshot.period = dimension ->> 'period'
        and snapshot.metric = dimension ->> 'metric'
        and snapshot.source = dimension ->> 'source'
    ), '[]'::jsonb)
  ) order by dimension ->> 'period', dimension ->> 'metric', dimension ->> 'source'), '[]'::jsonb)
  into v_static_dimensions
  from jsonb_array_elements(p_dimensions) dimension;

  return jsonb_build_object(
    'snapshot_run_id', v_snapshot_run_id,
    'row_counts', v_row_counts,
    'rows_inserted', v_inserted,
    'duration_ms', round(extract(epoch from (clock_timestamp() - v_started_at)) * 1000),
    'pricing_version', v_pricing_version,
    'generated_at', v_generated_at,
    'static_dimensions', v_static_dimensions,
    'shanghai_period_day', v_shanghai_day
  );
end;
$function$;

revoke all on function public.refresh_leaderboard_snapshot_dimensions(jsonb)
  from public;
revoke all on function public.refresh_leaderboard_snapshot_dimensions(jsonb)
  from anon;
grant execute on function public.refresh_leaderboard_snapshot_dimensions(jsonb)
  to project_admin;
